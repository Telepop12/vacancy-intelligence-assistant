_BASIS = ("вакансия", "компания", "отрасль")


def _stage_improve(pkg, api_key, vac, title, company, resume, facts, co) -> None:
    kb_impr = kb.improve_rules() or "— база знаний недоступна —"
    try:
        research = pr.get_practices(title, company, vac, pkg.company_profile, api_key=api_key)
    except Exception:
        # Доступность поиска не должна лишать кандидата вопросов по вакансии.
        research = pr.PracticeBrief(note="Внешний поиск недоступен. Отраслевые практики не добавлены.")
    data = _call_llm(api_key, _IMPR_SYSTEM, _IMPR_USER.format(
        title=title, company=company, vacancy_text=vac,
        resume_text=resume, facts=facts,
        trumps="; ".join(pkg.top_trumps) or "—",
        company_brief=co,
        practice_brief=pr.for_prompt(research),
        kb_improve=kb_impr,
    ), max_tokens=6000, materials=_materials(resume, facts))
    items = []
    known_ids = {p.id for p in research.practices}
    for raw in data.get("items") or []:
        if not isinstance(raw, dict):
            continue
        it = _mk(Improvement, raw)
        low = it.basis.lower()
        found = [(low.find(b), b) for b in _BASIS if b in low]
        it.basis = min(found)[1] if found else low.strip()   # первое из известных слов
        it.practice_ids = [value for value in (it.practice_ids or [])
                           if isinstance(value, str) and value in known_ids]
        if it.basis == "отрасль" and not it.practice_ids:
            continue
        if it.area or it.hypothesis:
            items.append(it)
    pkg.improvements = Improvements(
        frame=data.get("frame", ""), context=data.get("context", ""),
        # Форматируем тренды из проверенной структуры, чтобы финальный
        # пересказ не заменил практики абстрактными лозунгами.
        trends=[p.summary for p in research.practices],
        items=items[:6],
        sources=_clean_sources(data.get("sources"), kb_impr,
                               ["employers_official.md — п. 5, 6 (Газпром нефть, Билайн, НЛМК)",
                                "real_stories.md — «Банк кейсов и домашних заданий» (S5, S12, S16)",
                                "executive_search.md — п. 2.2"]),
        practices=research.practices,
        research_note=research.note or ("Подходящие внешние практики не найдены." if not research.practices else ""),
        research_rejected=research.rejected,
    )


def load_stories(path: Path | None = None) -> str:
    """
    Личный файл историй кандидата (вне git). Возвращает содержимое без
    заголовков и подсказок (строки «>»); пустая строка — если файла нет или он
    содержит только шаблон.
    """
    path = path or STORIES_PATH
    if not path.exists():
        return ""
    raw = path.read_text(encoding="utf-8")
    meaningful = [
        ln for ln in raw.splitlines()
        if ln.strip() and not ln.lstrip().startswith(("#", ">"))
    ]
    if len(" ".join(meaningful).strip()) < 40:
        return ""
    return raw


