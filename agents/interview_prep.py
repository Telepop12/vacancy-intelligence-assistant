def answer_user_question(package_id: str, question: str) -> PrepQA:
    """Answer a user-typed interviewer question and persist it in the package."""
    question = (question or "").strip()
    if not question:
        return PrepQA(question="", answer="", severity="user")

    pkg = load_saved_prep(package_id)
    api_key = _get_api_key()
    if not api_key:
        return PrepQA(question=question, answer="Нет OPENAI_API_KEY.", severity="user")

    try:
        resume = load_canonical_resume()
    except Exception as exc:
        return PrepQA(question=question, answer=f"Не удалось прочитать резюме: {exc}", severity="user")

    data = _call_llm(api_key, _ASK_SYSTEM, _ASK_USER.format(
        title=pkg.vacancy_title if pkg else "—",
        company=pkg.company if pkg else "—",
        interviewer_profile=pkg.interviewer_profile if pkg else "—",
        company_brief=cr.digest(pkg.company_profile, max_chars=6000) if pkg else "— справка отсутствует —",
        quantitative_brief=kb.quantitative_context(
            question, f"{pkg.vacancy_title}\n{pkg.company}\n{cr.digest(pkg.company_profile)}" if pkg else ""
        ) or "— подходящих проверенных ориентиров нет; используй данные условия и явные расчёты —",
        resume_text=resume,
        facts=load_facts() or "— факт-база пуста —",
        question=question,
    ), max_tokens=4000, materials=_materials(resume, load_facts() or "— факт-база пуста —"))

    understanding = str(data.get("understanding") or "").strip()
    lead = _norm_lead(str(data.get("lead") or ""))
    item = PrepQA(
        source=(data.get("note") or "ваш вопрос").strip() or "ваш вопрос",
        question=question,
        answer=str(data.get("answer", "")),
        severity="user",
        understanding=understanding,
        lead="опыт" if lead == "понимание" and not understanding else lead,
    )
    if pkg is not None:
        pkg.user_qa.append(item)
        _save(pkg)
    return item


